export function resolveTPMedicalIconName(name) {
  const direct =
    tpMedicalIconAliasMap[name] ?? tpMedicalIconAliasMap[name.trim()];
  if (direct) return direct;
  const normalized = name
    .trim()
    .toLowerCase()
    .replace(/[_.-]+/g, " ")
    .replace(/\s+/g, " ");
  return tpMedicalIconAliasMap[normalized] ?? null;
}
